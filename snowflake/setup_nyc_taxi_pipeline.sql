-- 1. A role for the pipeline
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS TRANSFORMER;
GRANT ROLE TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE TRANSFORMER TO USER LOHITKILARU;

-- 2. Compute and the database
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS TRANSFORM_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS NYC_TAXI;

GRANT USAGE ON WAREHOUSE TRANSFORM_WH TO ROLE TRANSFORMER;
GRANT OWNERSHIP ON DATABASE NYC_TAXI TO ROLE TRANSFORMER;

-- 3. Schemas and file format
USE ROLE TRANSFORMER;
USE WAREHOUSE TRANSFORM_WH;
USE DATABASE NYC_TAXI;

CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS STAGING;
CREATE SCHEMA IF NOT EXISTS MARTS;

CREATE FILE FORMAT IF NOT EXISTS RAW.PARQUET_FMT
    TYPE = PARQUET
    USE_LOGICAL_TYPE = TRUE;


-- 4. Connect Snowflake to S3
USE ROLE ACCOUNTADMIN;

CREATE STORAGE INTEGRATION IF NOT EXISTS S3_NYC_TAXI_INT
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'S3'
  ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = 'AWS ROLE ARN'
  STORAGE_ALLOWED_LOCATIONS = ('S3 Bucket ID');

GRANT USAGE ON INTEGRATION S3_NYC_TAXI_INT TO ROLE TRANSFORMER;


USE ROLE ACCOUNTADMIN;
ALTER STORAGE INTEGRATION S3_NYC_TAXI_INT
SET STORAGE_ALLOWED_LOCATIONS = ('S3 bucket ID');


-- 5. A named pointer to the bucket
USE ROLE TRANSFORMER;
USE WAREHOUSE TRANSFORM_WH;
USE DATABASE NYC_TAXI;

CREATE STAGE IF NOT EXISTS RAW.S3_RAW_STAGE
STORAGE_INTEGRATION = S3_NYC_TAXI_INT
URL = 'S3 Bucket ID'
FILE_FORMAT = RAW.PARQUET_FMT;